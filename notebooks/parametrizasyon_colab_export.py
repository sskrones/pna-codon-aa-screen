def run_sander(prmtop, inpcrd, out_log):
    cmd = ["sander", "-O", "-i", "sp_energy.in", "-p", prmtop, "-c", inpcrd,
           "-r", "/tmp/discard.rst7", "-o", out_log]
    return subprocess.run(cmd, capture_output=True, text=True)

def get_last_energy_line(log_path):
    with open(log_path) as f:
        lines = f.readlines()
    header_idx = None
    for i, line in enumerate(lines):
        if "NSTEP" in line and "ENERGY" in line:
            header_idx = i
    if header_idx is None:
        return None
    for j in range(header_idx + 1, len(lines)):
        if lines[j].strip():
            return lines[j].strip()
    return None

def parse_energy_value(line):
    if line is None:
        return None
    parts = line.split()
    try:
        return float(parts[1])
    except (IndexError, ValueError):
        return None

