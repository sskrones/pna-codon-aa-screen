def get_receptor_box(pdbqt_path, padding=6.0):
    xs, ys, zs = [], [], []
    with open(pdbqt_path) as f:
        for line in f:
            if line.startswith("ATOM") or line.startswith("HETATM"):
                xs.append(float(line[30:38])); ys.append(float(line[38:46])); zs.append(float(line[46:54]))
    center = [(min(xs)+max(xs))/2, (min(ys)+max(ys))/2, (min(zs)+max(zs))/2]
    size = [max(xs)-min(xs)+2*padding, max(ys)-min(ys)+2*padding, max(zs)-min(zs)+2*padding]
    return center, size

def parse_pose_pdbqt(path):
    coords = {}
    with open(path) as f:
        for line in f:
            if line.startswith("ATOM") or line.startswith("HETATM"):
                name = line[12:16].strip()
                coords[name] = (float(line[30:38]), float(line[38:46]), float(line[46:54]))
    return coords

def run_sander(mdin, prmtop, inpcrd, out_log, rst_out="/tmp/discard.rst7", ref=None, traj_out=None):
    cmd = ["sander", "-O", "-i", mdin, "-p", prmtop, "-c", inpcrd,
           "-r", rst_out, "-o", out_log]
    if traj_out:
        cmd += ["-x", traj_out]
    if ref:
        cmd += ["-ref", ref]
    return subprocess.run(cmd, capture_output=True, text=True)

def get_last_energy(log_path):
    try:
        with open(log_path) as f:
            lines = f.readlines()
    except FileNotFoundError:
        return None
    header_idx = None
    for i, line in enumerate(lines):
        if "NSTEP" in line and "ENERGY" in line:
            header_idx = i
    if header_idx is None:
        return None
    for j in range(header_idx + 1, len(lines)):
        if lines[j].strip():
            try:
                return float(lines[j].split()[1])
            except (IndexError, ValueError):
                return None
    return None

