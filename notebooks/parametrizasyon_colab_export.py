def get_receptor_box(pdbqt_path, padding=6.0):
    xs, ys, zs = [], [], []
    with open(pdbqt_path) as f:
        for line in f:
            if line.startswith("ATOM") or line.startswith("HETATM"):
                xs.append(float(line[30:38])); ys.append(float(line[38:46])); zs.append(float(line[46:54]))
    center = [(min(xs)+max(xs))/2, (min(ys)+max(ys))/2, (min(zs)+max(zs))/2]
    size = [max(xs)-min(xs)+2*padding, max(ys)-min(ys)+2*padding, max(zs)-min(zs)+2*padding]
    return center, size

def parse_pose_pdbqt(path):
    coords = {}
    with open(path) as f:
        for line in f:
            if line.startswith("ATOM") or line.startswith("HETATM"):
                name = line[12:16].strip()
                coords[name] = (float(line[30:38]), float(line[38:46]), float(line[46:54]))
    return coords

